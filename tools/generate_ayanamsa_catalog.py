"""Generate native/browser convention definitions from the Python catalog."""
from dataclasses import asdict
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ephemeris_oss.engine.conventions import AYANAMSA_CATALOG, AYANAMSA_CATALOG_VERSION

DEFAULT_RUST_OUTPUT = ROOT / "rust/ephemeris-core/src/ayanamsa_catalog.rs"
DEFAULT_JS_OUTPUT = ROOT / "web/ayanamsa-catalog.js"


def generated_sources(rust_output=DEFAULT_RUST_OUTPUT, js_output=DEFAULT_JS_OUTPUT):
    rows, metadata = [], []
    for index, definition in enumerate(AYANAMSA_CATALOG.values()):
        if definition.model in {"published_lahiri_anchor", "modern_reference_ecliptic"}:
            model = 0
        elif definition.model in {"star_anchor", "polar_anchor"}:
            model = 1
        elif definition.model == "galactic_plane":
            model = 2
        else:
            raise ValueError(f"No native operation for {definition.model}")
        ra, dec = definition.galactic_pole_icrs_deg or (0., 0.)
        values = (definition.reference_jd_tt or 0., definition.reference_offset_deg or 0.,
                  definition.reference_equinox_displacement_arcsec,
                  definition.sidereal_anchor_deg or 0., ra, dec)
        rows.append(f"    ({model}, " + ", ".join(repr(float(v)) for v in values) + "),")
        metadata.append({"id": index, **asdict(definition)})
    rust = ("// Generated by tools/generate_ayanamsa_catalog.py; do not edit.\n"
            f"// Catalog: {AYANAMSA_CATALOG_VERSION}\n"
            "pub const DEFINITIONS: &[(u8, f64, f64, f64, f64, f64, f64)] = &[\n"
            + "\n".join(rows) + "\n];\n")
    js = ("// Generated by tools/generate_ayanamsa_catalog.py; do not edit.\n"
          "export const LONG_TERM_AYANAMSA_CATALOG_VERSION = "
          + json.dumps(AYANAMSA_CATALOG_VERSION) + ";\nconst definitions = "
          + json.dumps(metadata, ensure_ascii=True, allow_nan=False, indent=2)
          + ";\nexport const LONG_TERM_AYANAMSA_CATALOG = Object.freeze(definitions.map(d =>\n"
          "  Object.freeze({...d, aliases: Object.freeze(d.aliases),\n"
          "    galactic_pole_icrs_deg: d.galactic_pole_icrs_deg === null ? null :\n"
          "      Object.freeze(d.galactic_pole_icrs_deg)})));\n")
    return {Path(rust_output): rust, Path(js_output): js}


def synchronize_generated_sources(sources, *, check):
    """Write generated bytes or return paths whose existing bytes are stale."""
    stale = []
    for path, source in sources.items():
        expected = source.encode("utf-8")
        if check:
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    return stale


def display_path(path):
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--rust-output", type=Path, default=DEFAULT_RUST_OUTPUT)
    parser.add_argument("--js-output", type=Path, default=DEFAULT_JS_OUTPUT)
    args = parser.parse_args()
    if args.rust_output.resolve() == args.js_output.resolve():
        parser.error("Rust and JavaScript outputs must be different paths")
    stale = synchronize_generated_sources(
        generated_sources(args.rust_output, args.js_output), check=args.check)
    if stale:
        raise SystemExit("Stale generated convention data: "
                         + ", ".join(display_path(path) for path in stale))
    print("Convention data checked" if args.check else "Convention data generated")


if __name__ == "__main__":
    main()
